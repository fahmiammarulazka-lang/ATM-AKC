export const formatTrialDurationLabel = (minutes?: number): string => {
  const m = Math.max(1, Math.round(minutes || 60));
  if (m >= 1440 && m % 1440 === 0) return `${m / 1440} Hari`;
  if (m >= 60 && m % 60 === 0) return `${m / 60} Jam`;
  if (m >= 60) {
    const h = Math.floor(m / 60);
    const rem = m % 60;
    return `${h} Jam ${rem} Menit`;
  }
  return `${m} Menit`;
};

