export function getAdminWarningPatternStyle(
  pattern?: AdminWarningBgPattern,
  tint = 'rgba(251, 191, 36, 0.14)'
): React.CSSProperties {
  switch (pattern) {
    case 'diagonal_stripes':
      return {
        backgroundImage: `repeating-linear-gradient(-45deg, ${tint} 0px, ${tint} 2px, transparent 2px, transparent 14px)`,
      };
    case 'hazard_chevron':
      return {
        backgroundImage: `repeating-linear-gradient(-45deg, ${tint} 0px, ${tint} 8px, transparent 8px, transparent 18px)`,
      };
    case 'dot_matrix':
      return {
        backgroundImage: `radial-gradient(${tint} 1.4px, transparent 1.4px)`,
        backgroundSize: '14px 14px',
      };
    case 'circuit_grid':
      return {
        backgroundImage: `linear-gradient(${tint} 1px, transparent 1px), linear-gradient(90deg, ${tint} 1px, transparent 1px)`,
        backgroundSize: '20px 20px',
      };
    case 'radial_spotlight':
      return {
        backgroundImage: `radial-gradient(circle at 18% 12%, ${tint}, transparent 58%), radial-gradient(circle at 86% 88%, ${tint}, transparent 52%)`,
      };
    case 'gold_shimmer':
      return {
        backgroundImage: `linear-gradient(125deg, transparent 20%, ${tint} 48%, transparent 74%)`,
      };
    case 'starburst_confetti':
      return {
        backgroundImage: `radial-gradient(${tint} 2px, transparent 2px), radial-gradient(${tint} 1.2px, transparent 1.2px)`,
        backgroundSize: '26px 26px',
        backgroundPosition: '0 0, 13px 13px',
      };
    case 'wave_mesh':
      return {
        backgroundImage: `radial-gradient(ellipse at 50% -10%, ${tint}, transparent 65%), repeating-radial-gradient(circle at 100% 100%, ${tint} 0, ${tint} 1px, transparent 1px, transparent 18px)`,
      };
    case 'security_grid':
      return {
        backgroundImage: `linear-gradient(45deg, ${tint} 1px, transparent 1px), linear-gradient(-45deg, ${tint} 1px, transparent 1px)`,
        backgroundSize: '18px 18px',
      };
    case 'none':
    default:
      return {};
  }
}

