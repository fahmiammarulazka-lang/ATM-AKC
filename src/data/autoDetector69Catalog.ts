export function createDefault69RulesEnabledMap(): Record<string, boolean> {
  const out: Record<string, boolean> = {};
  for (const rule of AUTO_DETECTOR_69_RULES) {
    out[rule.key] = true;
  }
  return out;
}

export function createDefault69ThresholdsMap(): Record<string, number> {
  const out: Record<string, number> = {};
  for (const rule of AUTO_DETECTOR_69_RULES) {
    out[rule.key] = rule.defaultThreshold;
  }
  return out;
}

export function createDefault69WindowsMap(): Record<string, number> {
  const out: Record<string, number> = {};
  for (const rule of AUTO_DETECTOR_69_RULES) {
    out[rule.key] = rule.defaultWindowMinutes;
  }
  return out;
}

export function getAutoDetectorRuleByKey(ruleKey: string): AutoDetectorRuleDefinition | undefined {
  return AUTO_DETECTOR_69_RULES.find((r) => r.key === ruleKey);
}
